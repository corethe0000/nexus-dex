//prints the Yul body of keccakF for Sk256.sol: lanes in memory at p + 32 * i, theta / rho-pi / chi unrolled, 24 round loop
//node tools/gen-keccak.mjs > /tmp/keccak.txt
const rotc = [1, 3, 6, 10, 15, 21, 28, 36, 45, 55, 2, 14, 27, 41, 56, 8, 25, 43, 62, 18, 39, 61, 20, 44];
const piln = [10, 7, 11, 17, 18, 3, 5, 16, 8, 21, 24, 4, 15, 23, 19, 13, 12, 2, 20, 14, 22, 9, 6, 1];
const L = (i) => (i === 0 ? 'p' : `add(p, ${32 * i})`);
const out = [];
const e = (s) => out.push('                ' + s);
for (let x = 0; x < 5; x++) {
  e(`let c${x} := xor(xor(xor(mload(${L(x)}), mload(${L(x + 5)})), xor(mload(${L(x + 10)}), mload(${L(x + 15)}))), mload(${L(x + 20)}))`);
}
for (let x = 0; x < 5; x++) {
  e(`{`);
  e(`    let d := xor(c${(x + 4) % 5}, rol(c${(x + 1) % 5}, 1))`);
  for (let y = 0; y < 25; y += 5) {
    e(`    mstore(${L(y + x)}, xor(mload(${L(y + x)}), d))`);
  }
  e(`}`);
}
e(`let t := mload(${L(1)})`);
for (let i = 0; i < 24; i++) {
  e(`{ let bc := mload(${L(piln[i])}) mstore(${L(piln[i])}, rol(t, ${rotc[i]})) t := bc }`);
}
for (let y = 0; y < 25; y += 5) {
  for (let x = 0; x < 5; x++) {
    e(`c${x} := mload(${L(y + x)})`);
  }
  for (let x = 0; x < 5; x++) {
    e(`mstore(${L(y + x)}, xor(c${x}, and(not(c${(x + 1) % 5}), c${(x + 2) % 5})))`);
  }
}
console.log(out.join('\n'));

